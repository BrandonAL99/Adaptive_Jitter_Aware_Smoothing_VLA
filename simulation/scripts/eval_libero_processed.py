"""
Evaluate a SmolVLA model on LIBERO with a pluggable action processor.

Two processor types are supported:

ActionProcessor (per-action)
  Applied to each action after the policy postprocessor, before env.step.
  Processors: identity, lowpass

ChunkProcessor (chunk-level)
  Applied to the full 50-step action chunk generated by the VLA at each step.
  The processor intercepts SmolVLA's _get_action_chunk via a policy hook, so
  the processed chunk is used before any action is returned or executed.
  Processors: ajas

To add a new processor:
  1. Add a class to libero_analysis/action_processors.py (ActionProcessor or ChunkProcessor)
  2. Register it in _REGISTRY at the bottom of that file
  3. Use --processor <name> here

Usage
-----
# Low-pass filter:
python simulation/scripts/eval_libero_processed.py \\
    --model HuggingFaceVLA/smolvla_libero \\
    --task libero_object --task-ids 0 --episodes 1 --seed 42 \\
    --processor lowpass --lowpass-cutoff 3.0 --lowpass-order 2 \\
    --output-dir libero_analysis/claude_results/lowpass_1ep \\
    --hf-dataset BrandonAL/claude_libero_lowpass_1ep

# AJAS (Adaptive Jitter-Aware Action Smoothing):
python simulation/scripts/eval_libero_processed.py \\
    --model HuggingFaceVLA/smolvla_libero \\
    --task libero_object --task-ids 0 --episodes 1 --seed 42 \\
    --processor ajas \\
    --output-dir libero_analysis/claude_results/ajas_1ep \\
    --hf-dataset BrandonAL/claude_libero_ajas_1ep

Notes
-----
- Requires the 'lerobot' conda env: conda activate lerobot
- For headless GPU: MUJOCO_GL=osmesa python simulation/scripts/eval_libero_processed.py ...
- Use --no-push to skip HuggingFace upload
"""

